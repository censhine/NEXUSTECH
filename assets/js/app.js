// Synchronize all segmented control buttons with the active theme and language
function updateControlButtons() {
  const isLight = window.currentTheme === 'light';
  const isZh = window.currentLang === 'zh';

  const btnDark = document.getElementById('btn-theme-dark');
  const btnLight = document.getElementById('btn-theme-light');
  const btnEn = document.getElementById('btn-lang-en');
  const btnZh = document.getElementById('btn-lang-zh');

  // Active button style:
  // In Light mode: crisp pure white background, dark text, subtle shadow, light border
  // In Dark mode: neon gradient background, white text
  if (btnDark && btnLight) {
    if (isLight) {
      btnLight.className = "active-pill flex items-center gap-1.5 px-3 py-1 rounded bg-blue-600 text-white font-bold shadow-sm transition-all";
      btnDark.className = "flex items-center gap-1.5 px-2.5 py-1 rounded text-slate-500 hover:text-slate-900 transition-all";
    } else {
      btnDark.className = "flex items-center gap-1.5 px-3 py-1 rounded bg-gradient-to-r from-blue-600 to-indigo-600 text-white font-bold shadow-md shadow-cyan-500/20 transition-all";
      btnLight.className = "flex items-center gap-1.5 px-2.5 py-1 rounded text-slate-400 hover:text-white transition-all";
    }
  }

  if (btnEn && btnZh) {
    if (isLight) {
      if (isZh) {
        btnZh.className = "active-pill px-3 py-1 rounded bg-blue-600 text-white font-bold shadow-sm transition-all";
        btnEn.className = "px-2.5 py-1 rounded text-slate-500 hover:text-slate-900 transition-all";
      } else {
        btnEn.className = "active-pill px-3 py-1 rounded bg-blue-600 text-white font-bold shadow-sm transition-all";
        btnZh.className = "px-2.5 py-1 rounded text-slate-500 hover:text-slate-900 transition-all";
      }
    } else {
      if (isZh) {
        btnZh.className = "px-3 py-1 rounded bg-gradient-to-r from-blue-600 to-cyan-500 text-white font-bold shadow-md shadow-cyan-500/20 transition-all";
        btnEn.className = "px-2.5 py-1 rounded text-slate-400 hover:text-white transition-all";
      } else {
        btnEn.className = "px-3 py-1 rounded bg-gradient-to-r from-blue-600 to-cyan-500 text-white font-bold shadow-md shadow-cyan-500/20 transition-all";
        btnZh.className = "px-2.5 py-1 rounded text-slate-400 hover:text-white transition-all";
      }
    }
  }
}

// Language switcher
window.setLanguage = function(targetLang) {
  window.currentLang = targetLang;

  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[targetLang] && translations[targetLang][key] !== undefined) {
      el.innerHTML = translations[targetLang][key];
    }
  });

  updateControlButtons();
  updateSpotlightBtnText();

  try {
    localStorage.setItem('nexus_lang', targetLang);
  } catch (e) {
    console.warn('LocalStorage unavailable:', e);
  }
};

window.toggleLanguage = function() {
  window.setLanguage(window.currentLang === 'en' ? 'zh' : 'en');
};

// Theme Controller (Cyber Dark vs Fresh Clean Tech)
